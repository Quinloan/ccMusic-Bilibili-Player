const assert = require('node:assert/strict');
const model = require('../renderer/library-model.js');
const tracks = [{ start: 0, end: 100, title: '甲' }, { start: 100, end: 300, title: '乙' }];
assert.equal(model.duration('1:20.5'), 80.5);
assert.equal(model.validateTracks(tracks, 300).length, 2);
assert.throws(() => model.validateTracks([{ start: 1, end: 100 }, tracks[1]], 300), /时间/);
assert.throws(() => model.validateTracks([tracks[0], { start: 110, end: 300 }], 300), /时间/);
assert.throws(() => model.validateTracks(tracks, 320), /遗漏/);
const cut = model.cutTrack(tracks, 1, '2:00');
assert.deepEqual(cut.map(t => [t.start, t.end]), [[0, 100], [100, 120], [120, 300]]);
assert.deepEqual(model.mergeTrack(cut, 2).map(t => [t.start, t.end]), [[0, 100], [100, 300]]);
assert.throws(() => model.cutTrack(tracks, 1, 999), /内部/);
const imported = model.importedFolders({ folders: [{ name: '测试', items: [{ bvid: 'BV1uuHd6cEhy', title: '<script>文本</script>', cookie: 'must-not-import', duration: '20:00', cover: 'file:///private' }] }] });
assert.equal(imported[0].items[0].duration, 1200);
assert.equal(imported[0].items[0].cover, '');
assert.equal(imported[0].items[0].cookie, undefined);
assert.throws(() => model.importedFolders({ folders: [{ name: '坏数据', items: [{ bvid: 'invalid' }] }] }), /BV/);
assert.throws(() => model.importedFolders({ folders: [{ name: '坏数据', items: [{ bvid: 'BV1uuHd6cEhy', split: true, startSec: 100, endSec: 20 }] }] }), /分段/);
const artwork = model.importedFolders({ folders: [{ name: '封面', items: [{ bvid: 'BV1uuHd6cEhy', songCover: 'https://p1.music.126.net/album.jpg', neteaseId: 347230 }] }] })[0].items[0];
assert.equal(artwork.songCover, 'https://p1.music.126.net/album.jpg'); assert.equal(artwork.neteaseId, '347230');
assert.equal(model.songCoverUrl('http://p1.music.126.net/album.jpg'), 'https://p1.music.126.net/album.jpg');
for (const unsafe of ['javascript:alert(1)', 'file:///secret.jpg', 'data:image/png;base64,abc', 'https://user:password@example.com/cover']) assert.equal(model.songCoverUrl(unsafe), '');
assert.equal(model.isVideoPart({ title: '坏女孩', vtitle: '徐良&小凌《坏女孩》', page: 1 }), false);
assert.equal(model.isVideoPart({ page: 1, partsCount: 2 }), true);
assert.equal(model.isVideoPart({ page: 1, partTitle: '01 坏女孩' }), true);
assert.equal(model.isVideoPart({ page: 1, partsCount: 1, partTitle: '旧标题' }), false);
assert.equal(model.isVideoPart({ page: 2 }), true);
assert.equal(model.isVideoPart({ split: true, page: 1, partsCount: 2, partTitle: '单曲' }), false);
console.log('PASS: complete nonoverlapping review, manual cut/merge, import validation, actual multi-P facts and credential exclusion');
